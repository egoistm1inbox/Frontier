//============================================================================================================================================
//                                                        GENERATEPRESETLIBRARY.MJS
//============================================================================================================================================
// 🧩 Presets/*.toml → Engine/PresetLibrary.js (browser bundle). Run after adding or editing a preset document:
//     node GeneratePresetLibrary.mjs
// Order comes from Scene.Order. Refuses to write when any document breaks a rule. FluidValidation.mjs fails when the bundle is stale.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseToml } from './Engine/TomlSubset.js';
import { validatePresetDocument } from './Engine/PresetDocumentValidation.js';
import { specificationHash, canonicalJson } from './Engine/LayerSpecificationValidation.js';

const Folder = path.dirname(fileURLToPath(import.meta.url));
export const PresetFolder = path.join(Folder, 'Presets');
export const PresetLibraryOutput = path.join(Folder, 'Engine', 'PresetLibrary.js');

export function readPresetDocuments()
{
    const files = fs.readdirSync(PresetFolder).filter((name) => name.endsWith('.toml')).sort();
    const documents = files.map((name) =>
    {
        const document = parseToml(fs.readFileSync(path.join(PresetFolder, name), 'utf8'));
        document.__file = name;
        return document;
    });
    documents.sort((a, b) => (a.Scene.Order ?? 1e9) - (b.Scene.Order ?? 1e9) || a.__file.localeCompare(b.__file));
    return documents;
}

export function generatePresetLibrary(documents = readPresetDocuments())
{
    const problems = documents.flatMap((document) => validatePresetDocument(document).map((problem) => `${document.__file}: ${problem}`));
    const ids = documents.map((document) => document.Scene.Id);
    for (const id of ids) if (ids.indexOf(id) !== ids.lastIndexOf(id)) problems.push(`duplicate preset Id ${id}`);
    if (problems.length) throw new Error('Preset documents are invalid:\n  ' + [...new Set(problems)].join('\n  '));
    const clean = documents.map((document) => { const copy = { ...document }; delete copy.__file; return copy; });
    const hash = specificationHash(clean.map((document) => JSON.parse(canonicalJson(document))));
    return [
        '//============================================================================================================================================',
        '//                                                           PRESETLIBRARY.JS',
        '//============================================================================================================================================',
        '// 📝 Generated by GeneratePresetLibrary.mjs from Presets/*.toml. Edit the TOML documents, never this file.',
        '',
        `export const PresetLibraryHash = '${hash}';`,
        `export const PresetDocuments = Object.freeze(${JSON.stringify(clean, null, 1)});`,
        '',
    ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    const output = generatePresetLibrary();
    fs.writeFileSync(PresetLibraryOutput, output);
    console.log(`Wrote ${path.relative(Folder, PresetLibraryOutput)} · ${readPresetDocuments().length} presets · hash ${output.match(/PresetLibraryHash = '([0-9a-f]+)'/)[1]}`);
}
