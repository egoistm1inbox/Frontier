#!/usr/bin/env node
// Batch-export every Alloy Studio pattern starter (patternStarterCatalog) into a
// native Vector Authoring TOML plus a Library.toml sidecar describing families,
// collection groups, palette variants and documented conversion deviations.
// Usage: node Automation/ExportPatternLibrary.mjs [output-directory]
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { patternStarterCatalog, patternStarter } from "../Experimental/TextureStudio/src/patternDocument.js";
import { textilePalettes } from "../Experimental/TextureStudio/src/patternLibrary.js";
import { convertPatternJson, serializeNativeToml } from "./ConvertWebPattern.mjs";

const Palettes = Object.keys(textilePalettes);
const slugify = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "pattern";
const tomlString = (value) => `"${String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("\n", "\\n").replaceAll("\r", "\\r")}"`;

function main() {
  const outDir = path.resolve(process.argv[2] || "EngineContent/PatternArchives/TextureStudio/starters");
  if (!Array.isArray(patternStarterCatalog) || !patternStarterCatalog.length) throw new Error("Pattern starter catalog is empty.");
  fs.mkdirSync(outDir, { recursive: true });
  const groups = [...new Set(patternStarterCatalog.map((entry) => entry.group))];
  const usedSlugs = new Set();
  const families = [];
  let files = 0, deviationNotes = 0, bytes = 0;
  for (const entry of patternStarterCatalog) {
    if (!entry.name || !entry.group) throw new Error("Catalog entry is missing its name or group.");
    let slug = slugify(entry.name);
    for (let salt = 2; usedSlugs.has(slug); salt++) slug = `${slugify(entry.name)}-${salt}`;
    usedSlugs.add(slug);
    const hasColorways = entry.colorways && Object.keys(entry.colorways).length > 0;
    const palettes = hasColorways ? Palettes : [Palettes[0]];
    const variantFiles = {}, variantDeviations = {};
    for (const palette of palettes) {
      const web = patternStarter(entry.name, palette);
      const converted = convertPatternJson(structuredClone(web));
      const file = hasColorways ? `${slug}-${palette.toLowerCase()}.vector.toml` : `${slug}.vector.toml`;
      const toml = serializeNativeToml(converted);
      fs.writeFileSync(path.join(outDir, file), toml, "utf8");
      bytes += toml.length;
      files++;
      variantFiles[palette] = file;
      if (converted.deviations?.length) {
        variantDeviations[palette] = converted.deviations;
        deviationNotes += converted.deviations.length;
      }
    }
    families.push({ name: entry.name, group: entry.group, description: entry.description || "",
      files: variantFiles, deviations: variantDeviations });
  }
  const lines = [
    "# Generated by Automation/ExportPatternLibrary.mjs from the Alloy Studio pattern starters — do not edit.",
    `format = "frontier.pattern_library"`,
    `version = 1`,
    `default_palette = ${tomlString(Palettes[0])}`,
    `palettes = [${Palettes.map(tomlString).join(", ")}]`,
    `groups = [${groups.map(tomlString).join(", ")}]`,
    "",
  ];
  for (const family of families) {
    lines.push("[[families]]",
      `name = ${tomlString(family.name)}`,
      `group = ${tomlString(family.group)}`,
      `description = ${tomlString(family.description)}`,
      `files = { ${Object.entries(family.files).map(([palette, file]) => `${palette} = ${tomlString(file)}`).join(", ")} }`);
    for (const [palette, notes] of Object.entries(family.deviations))
      lines.push(`deviations_${palette.toLowerCase()} = [${notes.map(tomlString).join(", ")}]`);
    lines.push("");
  }
  fs.writeFileSync(path.join(outDir, "Library.toml"), lines.join("\n"), "utf8");
  console.log(`Exported ${families.length} families (${files} palette TOMLs, ${(bytes / 1048576).toFixed(1)} MB) to ${outDir}`);
  console.log(`Collection groups: ${groups.join(" / ")}`);
  console.log(`Documented conversion deviations: ${deviationNotes}`);
}

try { main(); }
catch (error) { console.error(`Pattern library export failed: ${error.message}`); process.exitCode = 1; }
