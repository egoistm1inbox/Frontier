const IDENT_XFORM: LayerTransform = { x: 0, y: 0, z: 0, yaw: 0, scale: 1 };

function treeLayer(
  id: string,
  name: string,
  seed: number,
  overrides: Partial<TreeParams>,
  xform: Partial<LayerTransform> = {},
): GeneratorLayer {
  return {
    id,
    name,
    kind: 'tree',
    seed,
    visible: true,
    locked: false,
    transform: { ...IDENT_XFORM, ...xform },
    tree: { ...DEFAULT_TREE_PARAMS, ...overrides },
  };
}

