function flowerLayer(
  id: string,
  name: string,
  seed: number,
  species: FlowerSpecies,
  palette: FlowerColorPalette,
  overrides: Partial<FlowerParams> = {},
  xform: Partial<LayerTransform> = {},
): GeneratorLayer {
  const fp: FlowerParams = { ...DEFAULT_FLOWER_PARAMS, species };
  applyFlowerPalette(fp, palette);
  Object.assign(fp, overrides);
  return {
    id,
    name,
    kind: 'flower',
    seed,
    visible: true,
    locked: false,
    transform: { ...IDENT_XFORM, ...xform },
    flower: fp,
  };
}

function marineLayer(
  id: string,
  name: string,
  seed: number,
  species: MarineSpecies,
  palette?: MarineColorPalette,
  overrides: Partial<MarineParams> = {},
  xform: Partial<LayerTransform> = {},
): GeneratorLayer {
  const mp: MarineParams = { ...DEFAULT_MARINE_PARAMS };
  applyMarineSpeciesDefaults(mp, species);
  if (palette) applyMarinePalette(mp, palette);
  Object.assign(mp, overrides);
  return {
    id,
    name,
    kind: 'marine',
    seed,
    visible: true,
    locked: false,
    transform: { ...IDENT_XFORM, ...xform },
    marine: mp,
  };
}

