void Run(const RunConfiguration& Configuration, const float* Source, const float* Surface, float* Target, float* Output, const float* ValidSamples)
{
    const uint32_t ExtentPixels = Configuration.Extent;
    HistoryImage.Assign(static_cast<int>(ExtentPixels), static_cast<int>(ExtentPixels));
    for (size_t I = 0; I < HistoryImage.Texels.size(); ++I)
        HistoryImage.Texels[I] = vec4(0.0f, 0.0f, 0.0f, ValidSamples ? ValidSamples[I] : 1.0f);
    LoadImage(SourceImage, ExtentPixels, Source);
    LoadImage(SurfaceImage, ExtentPixels, Surface);
    LoadImage(TargetImage, ExtentPixels, Source);        // pre-fill: an untouched texel must be visibly untouched, not zero
    OutputImage.Assign(static_cast<int>(ExtentPixels), static_cast<int>(ExtentPixels));
    // V7 demodulation: the kernel parks the primary surface's albedo in the presentation image and the final level
    //    reads it back to remodulate. The mirror's streams feed radiance directly — unit albedo — so the parked
    //    value is 1 and every pre-demodulation expectation keeps its meaning unchanged.
    for (vec4& Texel : OutputImage.Texels) Texel = vec4(1.0f, 1.0f, 1.0f, 1.0f);

    DenoiseParameters.Extent[0]        = ExtentPixels;
    DenoiseParameters.Extent[1]        = ExtentPixels;
    DenoiseParameters.StepSize         = Configuration.StepSize;
    DenoiseParameters.Enabled          = Configuration.Enabled ? 1u : 0u;
    DenoiseParameters.NormalPower      = Configuration.NormalPower;
    DenoiseParameters.DepthScale       = Configuration.DepthScale;
    DenoiseParameters.LuminanceScale   = Configuration.LuminanceScale;
    DenoiseParameters.Exposure         = Configuration.Exposure;
    DenoiseParameters.FinalLevel       = Configuration.FinalLevel ? 1u : 0u;
    DenoiseParameters.ColourSaturation = Configuration.ColourSaturation;

    for (uint32_t Y = 0u; Y < ExtentPixels; ++Y)
        for (uint32_t X = 0u; X < ExtentPixels; ++X)
        {
            gl_GlobalInvocationID.x = X;
            gl_GlobalInvocationID.y = Y;
            AtrousDenoiseEntry();
        }

    if (Target != nullptr) StoreImage(TargetImage, ExtentPixels, Target);
    if (Output != nullptr) StoreImage(OutputImage, ExtentPixels, Output);
}

