//------------------------------------------------------------------------------------------------------------------------
//                                             ACCUMULATOR (kernel mirror)
//------------------------------------------------------------------------------------------------------------------------

void Accumulator::Resolve(const float SampleRadiance[3], float* OutRadiance, float* OutVariance)
{
    // ReSTIRViewport.slang `ResolveSurface`, in order: count += 1; mean += (x − mean)/count; moments += (luma,
    //    luma² − moments)/count; variance = max(E[x²] − E[x]², 0)/count; a first sample reports luma².
    Count += 1.0f;
    for (int C = 0; C < 3; ++C) Mean[C] += (SampleRadiance[C] - Mean[C]) / Count;

    const float Luma = SampleRadiance[0] * 0.2126f + SampleRadiance[1] * 0.7152f + SampleRadiance[2] * 0.0722f;
    Moments[0] += (Luma - Moments[0]) / Count;
    Moments[1] += (Luma * Luma - Moments[1]) / Count;

    float SampleVariance = Moments[1] - Moments[0] * Moments[0];
    if (SampleVariance < 0.0f) SampleVariance = 0.0f;
    float Variance = SampleVariance / Count;
    if (Count < 2.0f) Variance = Luma * Luma;

    OutRadiance[0] = Mean[0]; OutRadiance[1] = Mean[1]; OutRadiance[2] = Mean[2];
    *OutVariance = Variance;
}

